const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const ts=require("typescript");
const read=p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const compiled=ts.transpileModule(read("src/lib/learner-product-project.ts"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exportsObject={};
vm.runInNewContext(compiled,{exports:exportsObject,URL});
const {projectSections,emptyDossier,milestoneProgress,safeProjectLink,projectMilestones}=exportsObject;
test("dossier exposes 23 unique fields across seven sections",()=>{
 const fields=projectSections.flatMap(s=>s.fields);
 assert.equal(projectSections.length,7);
 assert.equal(fields.length,23);
 assert.equal(new Set(fields.map(f=>f.key)).size,23);
 assert.equal(Object.keys(emptyDossier()).length,23);
 assert.ok(Object.values(emptyDossier()).every(v=>v===""));
});
test("milestones require the exact verified workshop slugs, not draft completion or duplicate proofs",()=>{
 const lessons=projectMilestones[2].lessons;
 const evidence=lessons.map(lesson_slug=>({lesson_slug,score:80,xp:100}));
 const first=milestoneProgress(evidence.slice(0,4));
 assert.equal(first[0].complete,true);
 assert.equal(first[1].complete,false);
 assert.equal(first[2].complete,false);
 assert.equal(milestoneProgress(evidence.slice(0,8))[1].complete,true);
 assert.equal(milestoneProgress(evidence)[2].complete,true);
 assert.equal(milestoneProgress([evidence[0],evidence[0]])[0].count,1);
 assert.equal(milestoneProgress([{...evidence[0],xp:0},{...evidence[1],score:79}])[0].count,0);
 assert.equal(milestoneProgress(null)[0].available,false);
 assert.equal(milestoneProgress(null)[0].complete,false);
 const catalog=read("src/lib/v2-public-catalog.ts");
 assert.equal(new Set(lessons).size,16);
 for(const slug of lessons)assert.ok(catalog.includes('"slug": "'+slug+'"'),slug);
});
test("unsafe links are refused and private project actions are role-protected",()=>{
 assert.equal(safeProjectLink("javascript:alert(1)"),null);
 assert.equal(safeProjectLink("http://example.invalid"),null);
 assert.equal(safeProjectLink("https://user:pass@example.invalid"),null);
 assert.equal(safeProjectLink("https://example.invalid/repo"),"https://example.invalid/repo");
 const page=read("src/app/espace/projet/page.tsx");
 const action=read("src/app/espace/projet/actions.ts");
 const editor=read("src/components/learner-product-editor.tsx");
 assert.ok(page.includes('requireRole("learner")'));
 assert.ok(action.includes('requireRole("learner")'));
 assert.ok(page.includes('trainer_approved_with_xp_ledger'));
 assert.ok(action.includes('res?.status===409'));
 assert.ok(editor.includes('Ton texte est conservé'));
 assert.ok(editor.includes('Exporter le dossier'));
 assert.ok(!editor.includes("localStorage"));
 assert.ok(read("src/components/secure-academy-shell.tsx").includes('projectBase?projectBase+"/projet":"/espace/projet"'));
 assert.ok(read("src/app/espace/parcours/ingenierie-produit-ia/atelier/[slug]/page.tsx").includes('href="/espace/projet"'));
});
